import gradio as gr
import moviepy.editor as mp
import whisper
from textblob import TextBlob
from transformers import pipeline
import os

# Whisper for speech-to-text
whisper_model = whisper.load_model("base")

# Huggingface for emotion detection
emotion_pipeline = pipeline("sentiment-analysis")

def video_to_emotion(video_file):
    # 1. Extract audio from video
    video = mp.VideoFileClip(video_file)
    audio_path = "extracted_audio.wav"
    video.audio.write_audiofile(audio_path)

    # 2. Transcribe audio to text
    result = whisper_model.transcribe(audio_path)
    transcribed_text = result['text']

    # 3. Basic Sentiment Analysis
    blob = TextBlob(transcribed_text)
    polarity = blob.sentiment.polarity

    if polarity > 0:
        sentiment = "Positive"
    elif polarity < 0:
        sentiment = "Negative"
    else:
        sentiment = "Neutral"

    # 4. Emotion Detection
    emotion_result = emotion_pipeline(transcribed_text)[0]
    emotion_label = emotion_result['label']
    confidence = emotion_result['score']

    # 5. Create Output
    output = (
        f"📝 **Extracted Text from Video:**\n{transcribed_text}\n\n"
        f"💬 **Basic Sentiment:** {sentiment}\n\n"
        f"🎯 **Detected Emotion:** {emotion_label} ({confidence*100:.2f}% Confidence)"
    )

    # Clean temporary audio file
    if os.path.exists(audio_path):
        os.remove(audio_path)

    return output

interface = gr.Interface(
    fn=video_to_emotion,
    inputs=gr.Video(label="Upload your Social Media Video"),
    outputs=gr.Textbox(label="Extracted Post + Sentiment + Emotion"),
    title="Emotion Decoder - Video to Sentiment & Emotion Analysis",
    description="Upload a social media video. It will extract the text, paste it back, and analyze the emotional tone."
)

interface.launch(share=True)

